"""
ConnectHub AI Engine — CV Upload Schemas
=========================================

Pydantic v2 schemas for file upload responses and metadata tracking.

Strictly typed models:
  - UploadResponse: Public API response payload (no filesystem paths exposed).
  - UploadMetadata: Internal audit and session metadata (in-memory tracking).
"""

from __future__ import annotations

from datetime import datetime
from pydantic import BaseModel, ConfigDict, Field
from pydantic.alias_generators import to_camel


class UploadResponse(BaseModel):
    """
    Public response model returned when a CV file is successfully uploaded.

    Exposes only client-safe metadata. Internal filesystem paths are strictly excluded.
    """

    model_config = ConfigDict(
        populate_by_name=True,
        alias_generator=to_camel,
        json_schema_extra={
            "example": {
                "uploadId": "3d91d0d5-acde-4d4e-b29b-0a7cf8d89b3d",
                "originalFileName": "resume.pdf",
                "storedFileName": "3d91d0d5-acde-4d4e-b29b-0a7cf8d89b3d.pdf",
                "size": 542331,
                "mimeType": "application/pdf",
            }
        },
    )

    upload_id: str = Field(
        ...,
        description="Unique UUIDv4 identifier for the uploaded CV session.",
    )
    original_file_name: str = Field(
        ...,
        description="Original name of the uploaded CV file.",
    )
    stored_file_name: str = Field(
        ...,
        description="Sanitized unique filename assigned on disk (never user-controlled).",
    )
    size: int = Field(
        ...,
        description="File size in bytes.",
    )
    mime_type: str = Field(
        ...,
        description="MIME type of the uploaded file.",
    )


class UploadMetadata(BaseModel):
    """
    Internal metadata record for an uploaded CV file.

    Stored strictly in-memory during Phase 2.1.
    Includes full operational metadata, storage paths, and timestamp.
    """

    model_config = ConfigDict(
        populate_by_name=True,
        alias_generator=to_camel,
    )

    upload_id: str = Field(
        ...,
        description="Unique UUIDv4 identifier for the uploaded file session.",
    )
    original_file_name: str = Field(
        ...,
        description="Original name of the uploaded CV file.",
    )
    stored_file_name: str = Field(
        ...,
        description="Unique UUIDv4-based filename generated by the system and saved to disk.",
    )
    upload_timestamp: datetime = Field(
        ...,
        description="UTC timestamp when the upload occurred.",
    )
    file_size: int = Field(
        ...,
        description="Size of the uploaded file in bytes.",
    )
    mime_type: str = Field(
        ...,
        description="MIME type of the uploaded file (e.g. application/pdf).",
    )
    absolute_path: str = Field(
        ...,
        description="Full absolute filesystem path to the stored file.",
    )
    relative_path: str = Field(
        ...,
        description="Relative filesystem path from the project root.",
    )

    def to_response(self) -> UploadResponse:
        """
        Convert metadata to client-safe UploadResponse without exposing filesystem paths.
        """
        return UploadResponse(
            upload_id=self.upload_id,
            original_file_name=self.original_file_name,
            stored_file_name=self.stored_file_name,
            size=self.file_size,
            mime_type=self.mime_type,
        )
